import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import type { Plugin, PluginOption } from 'vite';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

const mocks = vi.hoisted(() => ({
  build: vi.fn<() => Promise<void>>(),
  builderConfigs: [] as Array<Record<string, unknown>>,
  loadConfig: vi.fn(),
}));

vi.mock('@sveltejs/load-config', () => ({
  loadConfig: mocks.loadConfig,
}));

vi.mock('@workflow/builders', () => ({
  createBuildQueue: () => (fn: () => Promise<void>) => fn(),
}));

vi.mock('@workflow/rollup', () => ({
  workflowTransformPlugin: () => ({ name: 'workflow:transform' }),
}));

vi.mock('@workflow/vite', () => ({
  workflowHotUpdatePlugin: () => ({ name: 'workflow:hot-update' }),
}));

vi.mock('./builder.js', () => ({
  SvelteKitBuilder: class {
    constructor(config: Record<string, unknown>) {
      mocks.builderConfigs.push(config);
    }

    build = mocks.build;
  },
}));

import { workflowPlugin } from './plugin.js';

const originalWorkingDir = process.cwd();

function kitPlugin(options: object = {}): Promise<Plugin[]> {
  return Promise.resolve([
    { name: 'vite-plugin-sveltekit-setup', api: { options } },
  ]);
}

async function resolvePlugins(
  plugins: PluginOption[],
  userPlugins: PluginOption[] = []
): Promise<void> {
  const [routes] = plugins as Plugin[];
  const hook = routes.config as {
    handler: (config: { plugins: PluginOption[] }) => Promise<void>;
  };
  await hook.handler({ plugins: [...userPlugins, plugins] });
}
let workingDir: string;

beforeEach(async () => {
  workingDir = await mkdtemp(join(tmpdir(), 'workflow-sveltekit-'));
  process.chdir(workingDir);
  workingDir = process.cwd(); // MacOS: resolves symlink of generated /var/folders/... through to /private/var/folders/...
  mocks.build.mockResolvedValue(undefined);
});

afterEach(async () => {
  process.chdir(originalWorkingDir);
  await rm(workingDir, { force: true, recursive: true });
  vi.clearAllMocks();
  mocks.builderConfigs.length = 0;
});

describe('workflowPlugin', () => {
  it('reads SvelteKit 3 routes from the SvelteKit plugin without loading the config', async () => {
    const routesDir = join(workingDir, 'app/routes');
    mocks.loadConfig.mockReturnValue(new Promise(() => {}));

    const plugins = workflowPlugin();
    await resolvePlugins(plugins, [
      kitPlugin({ files: { routes: routesDir } }),
    ]);

    expect(plugins[0]).toMatchObject({
      enforce: 'pre',
      config: { order: 'pre' },
    });
    expect(mocks.loadConfig).not.toHaveBeenCalled();
    expect(mocks.builderConfigs).toEqual([{ routesDir, workingDir }]);
    expect(mocks.build).toHaveBeenCalledOnce();
  });

  it('reads SvelteKit 2 routes from the SvelteKit plugin', async () => {
    const routesDir = join(workingDir, 'app/routes');

    await resolvePlugins(workflowPlugin(), [
      kitPlugin({ kit: { files: { routes: routesDir } } }),
    ]);

    expect(mocks.loadConfig).not.toHaveBeenCalled();
    expect(mocks.builderConfigs).toEqual([{ routesDir, workingDir }]);
  });

  it('loads svelte.config.js when the SvelteKit plugin has no options', async () => {
    const configPath = join(workingDir, 'svelte.config.js');
    await writeFile(configPath, 'export default {};');
    mocks.loadConfig.mockResolvedValue({
      config: {},
      configFilePath: configPath,
      configSource: 'svelte',
    });

    await resolvePlugins(workflowPlugin(), [
      { name: 'vite-plugin-sveltekit-setup' },
    ]);

    expect(mocks.loadConfig).toHaveBeenCalledWith(configPath, {
      traverse: false,
    });
    expect(mocks.builderConfigs).toEqual([
      { routesDir: join(workingDir, 'src/routes'), workingDir },
    ]);
    expect(mocks.build).toHaveBeenCalledOnce();
  });

  it('uses the default routes directory without any Svelte config', async () => {
    await resolvePlugins(workflowPlugin());

    expect(mocks.loadConfig).not.toHaveBeenCalled();
    expect(mocks.builderConfigs).toEqual([
      { routesDir: join(workingDir, 'src/routes'), workingDir },
    ]);
  });

  it('reuses routes generated by another Vite config context', async () => {
    const routesDir = join(workingDir, 'app/routes');
    await mkdir(join(workingDir, 'node_modules/.cache/workflow'), {
      recursive: true,
    });
    await mkdir(join(routesDir, '.well-known/workflow/v1/flow'), {
      recursive: true,
    });
    await writeFile(
      join(workingDir, 'node_modules/.cache/workflow/sveltekit-build.json'),
      JSON.stringify({ pid: process.pid, routesDir })
    );
    await writeFile(
      join(routesDir, '.well-known/workflow/v1/flow/+server.js'),
      ''
    );

    await resolvePlugins(workflowPlugin());

    expect(mocks.loadConfig).not.toHaveBeenCalled();
    expect(mocks.builderConfigs).toEqual([{ routesDir, workingDir }]);
    expect(mocks.build).not.toHaveBeenCalled();
  });

  it('keeps the SDK in the server bundle for builds only', async () => {
    mocks.loadConfig.mockResolvedValue({
      config: {},
      configFilePath: join(workingDir, 'vite.config.ts'),
      configSource: 'vite',
    });

    const [pending] = workflowPlugin();
    const plugin = (await pending).find(
      (candidate) => candidate.name === 'workflow:sveltekit'
    );
    const config = plugin?.config as (
      config: object,
      env: { command: 'build' | 'serve'; mode: string }
    ) => { ssr: { noExternal: Array<string | RegExp> } } | undefined;

    expect(config({}, { command: 'serve', mode: 'development' })).toBe(
      undefined
    );

    const noExternal = config({}, { command: 'build', mode: 'production' })?.ssr
      .noExternal;
    const bundled = (dep: string) =>
      noExternal?.some((rule) =>
        typeof rule === 'string' ? rule === dep : rule.test(dep)
      );
    expect(bundled('workflow')).toBe(true);
    expect(bundled('@workflow/world-postgres')).toBe(true);
    expect(bundled('workflow-other')).toBe(false);
    expect(bundled('zod')).toBe(false);
  });

  it('passes source map options to the builder', async () => {
    await resolvePlugins(workflowPlugin({ sourcemap: 'external' }), [
      kitPlugin(),
    ]);

    expect(mocks.builderConfigs).toEqual([
      {
        routesDir: join(workingDir, 'src/routes'),
        workingDir,
        sourcemap: 'external',
      },
    ]);
  });
});
